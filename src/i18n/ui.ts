const ui: Record<Locale, Partial<Record<UiKey, string>>> = { en, es, ca };

/** Names of the languages as they appear inside a sentence of each locale. */
const languageInSentence: Record<Locale, Record<Locale, string>> = {
  en: { en: 'English', es: 'Spanish', ca: 'Catalan' },
  es: { en: 'inglés', es: 'español', ca: 'catalán' },
  ca: { en: 'anglès', es: 'castellà', ca: 'català' },
};

export function languageIn(locale: Locale, of: Locale) {
  return languageInSentence[locale][of];
}

export function useTranslations(locale: Locale) {
  return (key: UiKey, vars: Record<string, string | number> = {}) => {
    let s = ui[locale][key] ?? en[key];
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export function isLocale(x: string | undefined): x is Locale {
  return (locales as readonly string[]).includes(x ?? '');
}

/** Absolute path inside the site, honoring the configured base path. */
export function href(...segments: string[]) {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  const path = segments.filter(Boolean).join('/');
  return `${base}/${path}${path && !path.includes('#') && !path.includes('?') ? '/' : ''}`;
}
